"""Fits the speech-or-music logistic regression on the reference clips and checks it on clips it
has never seen. Features come from rovno_features (the exact code the app runs).
Usage: python train_classifier.py <rovno_features.exe> <refs dir> <ClassifierWeights.inc> [test_speech_dir test_music_dir]"""
import csv
import glob
import os
import subprocess
import sys
import tempfile

import numpy as np

EXE, REFS, OUT = sys.argv[1], sys.argv[2], sys.argv[3]
TESTS = sys.argv[4:6]
NAMES = ["pauses", "syllable", "bass", "air", "flux"]


def features(wavs, label):
    with tempfile.TemporaryDirectory() as tmp:
        path = os.path.join(tmp, "f.csv")
        for w in wavs:
            subprocess.run([EXE, w, str(label), path], check=True, capture_output=True)
        rows = list(csv.reader(open(path, encoding="utf-8", errors="replace")))
    clips = [r[0] for r in rows]
    X = np.array([[float(v) for v in r[2:7]] for r in rows])
    y = np.array([int(r[1]) for r in rows])
    return clips, X, y


def fit(X, y, l2=0.05, iters=4000, lr=0.2):
    mean, scale = X.mean(axis=0), X.std(axis=0) + 1e-6
    Z = (X - mean) / scale
    w, b = np.zeros(Z.shape[1]), 0.0
    for _ in range(iters):
        p = 1 / (1 + np.exp(-(Z @ w + b)))
        w -= lr * (Z.T @ (p - y) / len(y) + l2 * w)
        b -= lr * np.mean(p - y)
    return w, b, mean, scale


def predict(model, X):
    w, b, mean, scale = model
    return 1 / (1 + np.exp(-(((X - mean) / scale) @ w + b)))


sc, Xs, ys = features(sorted(glob.glob(os.path.join(REFS, "speech", "*.wav"))), 1)
mc, Xm, ym = features(sorted(glob.glob(os.path.join(REFS, "music", "*.wav"))), 0)
clips = sc + mc
X, y = np.vstack([Xs, Xm]), np.concatenate([ys, ym])
print(f"{len(y)} windows ({ys.sum()} speech, {len(ym)} music)")
for i, n in enumerate(NAMES):
    print(f"  {n:9s} speech {Xs[:, i].mean():7.3f}  music {Xm[:, i].mean():7.3f}")

# Leave-one-clip-out: how well does it do on a clip it was not trained on?
correct = 0
for c in sorted(set(clips)):
    tr = np.array([k != c for k in clips])
    model = fit(X[tr], y[tr])
    p = predict(model, X[~tr])
    correct += np.sum((p > 0.5) == y[~tr])
print(f"leave-one-clip-out accuracy per 4 s window: {100 * correct / len(y):.1f}%")

model = fit(X, y)
w, b, mean, scale = model
if TESTS:
    for d, label in zip(TESTS, (1, 0)):
        tc, Xt, yt = features(sorted(glob.glob(os.path.join(d, "*.wav"))), label)
        p = predict(model, Xt)
        for c in sorted(set(tc)):
            sel = np.array([k == c for k in tc])
            print(f"  unseen {'speech' if label else 'music '} {os.path.basename(c):28s} P(speech) median {np.median(p[sel]):.2f}, "
                  f"right {100 * np.mean((p[sel] > 0.5) == label):.0f}% of windows")

with open(OUT, "w", encoding="utf-8", newline="\n") as f:
    f.write("// Generated by tools/train_classifier.py: logistic regression on 4 s windows of well-produced\n")
    f.write("// speech and music (RU and EN). Order: bias, pauses, syllable, bass, air, flux; then mean and scale.\n")
    f.write("inline constexpr ClassifierWeights kClassifier = { %.4ff, %s,\n    { %s }, { %s } };\n" % (
        b, ", ".join(f"{v:.4f}f" for v in w), ", ".join(f"{v:.4f}f" for v in mean), ", ".join(f"{v:.4f}f" for v in scale)))
print("weights:", " ".join(f"{n}={v:+.2f}" for n, v in zip(NAMES, w)), f"bias={b:+.2f}")
