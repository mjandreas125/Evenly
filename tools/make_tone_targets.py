"""Builds the 'range of good recordings' the tone corrector compares against.

Every reference clip goes through rovno_render (so the analysis is exactly what the app sees);
its long-term spectrum is averaged over the audible frames with the same gate as ToneCorrector,
normalised to the 500 Hz - 2 kHz mean, and the corridor per third octave is the 10th..90th
percentile across the clips, widened by a margin. Only these averaged numbers end up in the app.

Usage: python make_tone_targets.py <rovno_render.exe> <refs dir with speech/ and music/> <ToneTargets.inc>"""
import csv
import glob
import os
import subprocess
import sys
import tempfile

import numpy as np

RENDER, REFS, OUT = sys.argv[1], sys.argv[2], sys.argv[3]
BANDS = [50, 63, 80, 100, 125, 160, 200, 250, 315, 400, 500, 630, 800, 1000, 1250, 1600, 2000, 2500, 3150,
         4000, 5000, 6300, 8000, 10000, 12500, 16000]
MID = [i for i, f in enumerate(BANDS) if 500 <= f <= 2000]


def shape_of(wav):
    with tempfile.TemporaryDirectory() as tmp:
        csv_path = os.path.join(tmp, "frames.csv")
        subprocess.run([RENDER, wav, os.path.join(tmp, "out.wav"), "--loudness", "off", "--frames", csv_path],
                       check=True, capture_output=True)
        rows = list(csv.reader(open(csv_path)))
    level, acc, n = -70.0, np.zeros(len(BANDS)), 0
    for r in rows:
        lufs = float(r[1])
        bands = np.array([float(v) for v in r[4:4 + len(BANDS)]])
        level = lufs if lufs > level else level + (lufs - level) * 0.02
        if lufs < -55 or lufs < level - 12:
            continue
        acc += 10 ** (bands / 10)
        n += 1
    db = 10 * np.log10(acc / max(n, 1) + 1e-20)
    return db - db[MID].mean(), n


def corridor(kind, margin):
    shapes = []
    for wav in sorted(glob.glob(os.path.join(REFS, kind, "*.wav"))):
        s, n = shape_of(wav)
        if n < 200:
            print(f"  skip {wav} (only {n} audible frames)")
            continue
        shapes.append(s)
        print(f"  {os.path.basename(wav)}  " + " ".join(f"{v:5.1f}" for v in s[::3]))
    S = np.array(shapes)
    lo = np.percentile(S, 10, axis=0) - margin
    hi = np.percentile(S, 90, axis=0) + margin
    med = np.median(S, axis=0)
    print(f"{kind}: {len(shapes)} clips")
    return lo, hi, med


def fmt(name, lo, hi, med):
    a = ", ".join(f"{v:.1f}f" for v in lo)
    b = ", ".join(f"{v:.1f}f" for v in hi)
    m = ", ".join(f"{v:.1f}f" for v in med)
    return f"inline constexpr Corridor {name} = {{\n    {{ {a} }},\n    {{ {b} }},\n    {{ {m} }} }};\n"


sp_lo, sp_hi, sp_med = corridor("speech", 1.5)
mu_lo, mu_hi, mu_med = corridor("music", 2.0)
with open(OUT, "w", encoding="utf-8", newline="\n") as f:
    f.write("// Generated by tools/make_tone_targets.py from the average spectra of well-produced speech\n")
    f.write("// (podcasts, lectures, interviews; RU and EN) and music of many genres. Per third octave, 50 Hz -\n")
    f.write("// 16 kHz, dB relative to the 500 Hz - 2 kHz mean: the 10th..90th percentile plus a margin, and the median.\n")
    f.write(fmt("kSpeechCorridor", sp_lo, sp_hi, sp_med))
    f.write(fmt("kMusicCorridor", mu_lo, mu_hi, mu_med))
print("wrote", OUT)
for name, lo, hi in (("speech", sp_lo, sp_hi), ("music", mu_lo, mu_hi)):
    print(name + " lo " + " ".join(f"{v:5.1f}" for v in lo))
    print(name + " hi " + " ".join(f"{v:5.1f}" for v in hi))
