#pragma once
// Fixes the tone of a bad recording, slowly and only as far as needed. It averages the incoming
// spectrum over the audible parts (pauses ignored), compares its shape with the range that good
// recordings of the same kind fall into, and computes 10-band EQ gains that bring whatever lies
// outside that range back to its edge. Good recordings get no correction.
#include "../dsp/FxCore.h"
#include "../dsp/Shared.h"
#include <algorithm>
#include <cmath>
#include <complex>

namespace rv
{
enum class Content : int { Speech = 0, Music = 1 };

// Range of good recordings: band level relative to the 500 Hz - 2 kHz mean, per third octave,
// and their median.
struct Corridor { float lo[kBands], hi[kBands], median[kBands]; };
#include "ToneTargets.inc"   // kSpeechCorridor, kMusicCorridor (generated by tools/make_tone_targets.py)

class ToneCorrector
{
public:
    ToneCorrector() { buildResponse(); reset(); }

    void reset()
    {
        for (auto& p : power) p = 0;
        active = 0; sinceUpdate = 0; level = -70;
        for (auto& g : gains) g = 0;
        for (auto& s : shape) s = 0;
    }
    void setContent (Content c) { content = c; }
    void setStrength (float s) { strength = std::clamp (s, 0.0f, 1.0f); }
    // width > 0: aim at the median of good recordings, leaving +-width dB alone (dead zone);
    // width = 0: only fix what lies outside the 10..90 % range of good recordings.
    void setWidth (float w) { width = std::max (0.0f, w); }
    // Start from what was learned for this source; the estimate still has to build up.
    void setStart (const float g[10]) { for (int i = 0; i < 10; ++i) gains[i] = g[i]; }

    const float* correction() const { return gains; }
    const float* spectrumShape() const { return shape; }   // for the UI
    float confidence() const { return (float) std::min (1.0, active / (kFps * 8.0)); }

    // Feed one analysis frame (about 23 per second). Returns true when the correction changed.
    bool push (const AnalysisFrame& f)
    {
        level = f.lufs > level ? f.lufs : level + (f.lufs - level) * 0.02f;   // fast up, slow down
        if (f.lufs < -55 || f.lufs < level - 12) return false;               // pause or near-silence
        const double a = active < kFps * 4 ? 1.0 / (active + 1) : 1.0 / (kFps * 15.0);   // ~15 s memory
        for (int b = 0; b < kBands; ++b) power[b] += a * (std::pow (10.0, f.bandsDb[b] / 10.0) - power[b]);
        ++active;
        if (++sinceUpdate < (int) (kFps * 2) || active < kFps * 4) return false;
        sinceUpdate = 0;
        return update();
    }

private:
    static constexpr double kFps = 48000.0 / 2048.0;

    bool update()
    {
        double mid = 0;
        int n = 0;
        for (int b = 0; b < kBands; ++b)
            if (kBandHz[b] >= 500 && kBandHz[b] <= 2000) { mid += 10 * std::log10 (power[b] + 1e-20); ++n; }
        mid /= n;
        const Corridor& c = content == Content::Speech ? kSpeechCorridor : kMusicCorridor;
        // Wanted change per third octave: whatever lies outside the corridor, back to its edge.
        double want[kBands], w[kBands], dev[kBands];
        for (int b = 0; b < kBands; ++b) shape[b] = (float) (10 * std::log10 (power[b] + 1e-20) - mid);
        for (int b = 0; b < kBands; ++b)
        {
            // Half-octave smoothing: follow the overall tilt, not the natural peaks of one song or voice.
            double s = 0, n2 = 0;
            for (int k = std::max (0, b - 1); k <= std::min (kBands - 1, b + 1); ++k) { s += shape[k]; n2 += 1; }
            const double sm = s / n2;
            const double lo = width > 0 ? c.median[b] - width : c.lo[b], hi = width > 0 ? c.median[b] + width : c.hi[b];
            dev[b] = sm > hi ? hi - sm : (sm < lo ? lo - sm : 0.0);
        }
        for (int b = 0; b < kBands; ++b)
        {
            double d = dev[b];
            const bool empty = shape[b] < -40;                       // nothing there to bring up, only noise
            if (d > 0 && (empty || (content == Content::Speech && kBandHz[b] < 150))) d = 0;
            want[b] = std::clamp (d * strength, -8.0, 6.0);
            w[b] = (kBandHz[b] < 60 || kBandHz[b] > 14000) ? 0.2 : 1.0;
        }
        // Least-squares fit of the 10 EQ gains to the wanted curve (the bands overlap).
        double A[10][11] {};
        for (int i = 0; i < 10; ++i)
        {
            for (int j = 0; j < 10; ++j)
            {
                double s = 0;
                for (int b = 0; b < kBands; ++b) s += resp[b][i] * w[b] * resp[b][j];
                A[i][j] = s + (i == j ? 0.05 : 0.0);
            }
            double r = 0;
            for (int b = 0; b < kBands; ++b) r += resp[b][i] * w[b] * want[b];
            A[i][10] = r;
        }
        solve (A);
        bool changed = false;
        for (int i = 0; i < 10; ++i)
        {
            const float target = (float) std::clamp (A[i][10], -6.0, 6.0);
            const float step = std::clamp (target - gains[i], -1.0f, 1.0f);   // at most 1 dB per 2 s
            if (std::abs (step) >= 0.05f) { gains[i] = std::round ((gains[i] + step) * 10) / 10; changed = true; }
        }
        return changed;
    }

    // dB response at each third octave of each EQ band set to +6 dB, per dB of gain.
    void buildResponse()
    {
        const float fs = 48000;
        const float Q = fx::oldBandQ();
        for (int k = 0; k < 10; ++k)
        {
            const fx::Peak p = fx::calcParametric (fs, fx::kEqFreqs[k], 6.0f, Q);
            for (int b = 0; b < kBands; ++b)
            {
                const double om = 2 * 3.141592653589793 * kBandHz[b] / fs;
                // H(z) = (b0 + b1 z^-1 + b2 z^-2) / (1 + b1 z^-1 + a2 z^-2), a1 == b1
                const std::complex<double> z1 = std::polar (1.0, -om), z2 = z1 * z1;
                const auto num = (double) p.b0 + (double) p.b1 * z1 + (double) p.b2 * z2;
                const auto den = 1.0 + (double) p.b1 * z1 + (double) p.a2 * z2;
                resp[b][k] = 20 * std::log10 (std::abs (num / den)) / 6.0;
            }
        }
    }

    static void solve (double A[10][11])
    {
        for (int c = 0; c < 10; ++c)
        {
            int piv = c;
            for (int r = c + 1; r < 10; ++r) if (std::abs (A[r][c]) > std::abs (A[piv][c])) piv = r;
            for (int k = 0; k < 11; ++k) std::swap (A[c][k], A[piv][k]);
            const double d = A[c][c];
            if (std::abs (d) < 1e-12) continue;
            for (int k = c; k < 11; ++k) A[c][k] /= d;
            for (int r = 0; r < 10; ++r)
            {
                if (r == c) continue;
                const double f = A[r][c];
                for (int k = c; k < 11; ++k) A[r][k] -= f * A[c][k];
            }
        }
    }

    Content content = Content::Speech;
    float strength = 0.8f, width = 0.0f;
    double power[kBands] {};
    double resp[kBands][10] {};
    long active = 0;
    int sinceUpdate = 0;
    float level = -70;
    float gains[10] {};
    float shape[kBands] {};
};
} // namespace rv
